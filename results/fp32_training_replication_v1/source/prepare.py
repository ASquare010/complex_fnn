"""Verify H116 and freeze the new initial-state recipe before scientific work."""

import hashlib
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path("results/fp32_training_replication_v1")
OLD = Path("results/fp32_decoder_resource_v1")


def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def sha(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


assert not (ROOT / "protocol.json").exists()
prior_path = Path("results/verification/fp32_decoder_resource_final_v1.json")
receipt, previous = read(prior_path), read(OLD / "protocol.json")
assert receipt["status"] == "PASS" and not receipt["broad_goal_achieved"]
assert receipt["qualified_pairs"] == [
    dict(scope="narrow_wikitext2", policy="fp32_default_chunks"),
    dict(scope="narrow_tinystories", policy="fp32_default_chunks"),
]
for field in ("files", "tensor_hashes", "local_metric_hashes"):
    for path, digest in receipt[field].items():
        assert sha(path) == digest, path
for path, info in receipt["packed"].items():
    assert sha(path) == info["sha256"]
for field in ("sources", "maintained_files"):
    for path, digest in previous[field].items():
        assert sha(path) == digest, path
space = shutil.disk_usage(Path.cwd())
assert space.free > 20 * 2**30, "The planned local checkpoints require storage headroom"
policies = ["bf16_default_native", "fp32_default_native", "fp32_default_chunks"]
cfg = next(f["model_config"] for f in previous["fixtures"] if f["scope"] == "narrow_wikitext2")
fixtures = []
for dataset in ("wikitext2", "tinystories"):
    for seed in (101, 113, 127):
        index = len(fixtures)
        order = policies[index % 3 :] + policies[: index % 3]
        if index % 2:
            order.reverse()
        label = f"{dataset}_s{seed}"
        fixtures.append(
            dict(
                label=label,
                scope=dataset,
                dataset=dataset,
                batch=8,
                context=512,
                seed=seed,
                source_policy="fresh_initialization",
                source_step=0,
                checkpoint=(ROOT / "initial" / label / "step0.pt").as_posix(),
                model_config=cfg.copy(),
                policy_order=order,
            )
        )
before = ROOT / "before_documents"
before.mkdir(exist_ok=False)
documents = {}
for name in previous["before_documents"]:
    path = before / (name.replace("/", "__") if name != ".gitignore" else "gitignore")
    path.write_bytes(Path(name).read_bytes())
    documents[name] = dict(sha256=sha(name), preserved_path=path.as_posix())
sources = {
    **previous["sources"],
    **{
        p.as_posix(): sha(p)
        for p in (*ROOT.glob("source/*.py"), Path("research/fp32_training_replication_plan.md"))
    },
}
protocol = dict(
    study="H117",
    previous_goal_turn="progress",
    sources=sources,
    maintained_files=previous["maintained_files"],
    previous_receipt_sha256=sha(prior_path),
    previous_scientific_records={
        p.as_posix(): sha(p)
        for p in (OLD / "result.json", OLD / "summary.json", OLD / "audit.json")
    },
    git_head=subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip(),
    before_documents=documents,
    datasets=previous["datasets"],
    fixtures=fixtures,
    checkpoint_hashes={},
    initial_state_recipe="Six CPU step-zero models and empty Adam states, generated by frozen initialize.py before CUDA training",
    policies=policies,
    seeds=[101, 113, 127],
    cases=18,
    steps_per_case=800,
    warmup_steps=20,
    optimizer_updates=14400,
    training_targets=58982400,
    profile_backward_passes=14418,
    qualification_backward_passes=24,
    planned_audit_backward_passes=12,
    planned_native_scores=60,
    planned_trained_checkpoints=54,
    disk_free_bytes_before=space.free,
    fresh_training_runs=18,
    broad_goal_achieved=False,
)
(ROOT / "protocol.json").write_text(json.dumps(protocol, indent=2) + "\n")
(ROOT / "runs").mkdir(exist_ok=False)
print(f"Frozen {len(sources)} sources and 18 fresh trials; free disk {space.free / 2**30:.1f} GiB")
